    @Test
    public void matchesJdkOnRandomPatterns() {
        RegexDifferentialCases cases = new RegexDifferentialCases(42);
        StringBuilder failures = new StringBuilder();
        String[] block = new String[CASES_PER_BLOCK];
        int index = 0;
        for (int b = 0; b < EXPECTED_BLOCK_HASHES.length; ++b) {
            int hash = 0;
            int size = 0;
            for (int i = 0; i < CASES_PER_BLOCK; ++i, ++index) {
                String pattern = cases.nextPattern();
                String input = cases.nextInput();
                if (Arrays.binarySearch(KNOWN_GAPS, index) >= 0) {
                    continue;
                }
                block[size] = RegexDifferentialCases.describe(pattern, input);
                hash = hash * 31 + block[size++].hashCode();
            }
            if (hash != EXPECTED_BLOCK_HASHES[b]) {
                failures.append("Block ").append(b).append(" differs from the JDK:\n");
                for (int i = 0; i < size; ++i) {
                    failures.append("  ").append(block[i]).append('\n');
                }
            }
        }
        assertEquals("", failures.toString());
    }

    /*
     * Known gaps. Most are captures of an iteration that matches the empty string: the JDK reports no capture for a
     * group that can only match the empty string, as in (\b){0,2}, and TeaVM reports the empty capture. The others
     * come from captures that a possessive group leaves behind after a failed attempt at an earlier start, as in
     * ((a?)?){0,2}+b on "ccaba".
     */
    @Test
    @Disabled("TeaVM still differs from the JDK on captures of empty iterations and after possessive groups")
    public void knownGaps() {
        RegexDifferentialCases cases = new RegexDifferentialCases(42);
        StringBuilder failures = new StringBuilder();
        int gap = 0;
        for (int index = 0; gap < KNOWN_GAPS.length; ++index) {
            String pattern = cases.nextPattern();
            String input = cases.nextInput();
            if (index == KNOWN_GAPS[gap]) {
                String actual = RegexDifferentialCases.describe(pattern, input);
                if (!actual.equals(KNOWN_GAPS_EXPECTED[gap])) {
                    failures.append("  JDK ").append(KNOWN_GAPS_EXPECTED[gap]).append("\n  got ").append(actual)
                            .append('\n');
                }
                ++gap;
            }
        }
        assertEquals("", failures.toString());
    }
